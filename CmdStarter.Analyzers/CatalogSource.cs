using System.Text;

namespace CyberInternauts.CmdStarter.Analyzers;

// Writes the text of the generated catalog. The types are already sorted and written as global:: names.
internal static class CatalogSource
{
    internal const string FileName = "CommandCatalog.g.cs";

    private const string CatalogNamespace = "global::CyberInternauts.CmdStarter.Catalog";

    // "My.App-Tests" gives "CommandCatalog_My_App_Tests": two assemblies that see each other (InternalsVisibleTo) never see two internal types of the same name.
    internal static string ClassName(string? assemblyName)
    {
        var builder = new StringBuilder("CommandCatalog_");
        foreach (var character in assemblyName ?? string.Empty)
        {
            builder.Append(char.IsLetterOrDigit(character) || character == '_' ? character : '_');
        }

        return builder.ToString();
    }

    internal static string Write(string className, string version, IReadOnlyList<string> commands, IReadOnlyList<string> methodClasses, IReadOnlyList<string> globalOptions, IReadOnlyList<string> symbolTypes, IReadOnlyList<string> obsoleteDiagnosticIds)
    {
        var generatedNamespace = "global::CyberInternauts.CmdStarter.Generated";
        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("#nullable enable\n");
        builder.Append("#pragma warning disable CS0612, CS0618");
        foreach (var obsoleteDiagnosticId in obsoleteDiagnosticIds)
        {
            builder.Append(", ").Append(obsoleteDiagnosticId);
        }

        builder.Append('\n');
        builder.Append('\n');
        builder.Append("[assembly: ").Append(CatalogNamespace).Append(".CommandCatalog(typeof(").Append(generatedNamespace).Append('.').Append(className).Append("))]\n");
        builder.Append('\n');
        builder.Append("namespace CyberInternauts.CmdStarter.Generated;\n");
        builder.Append('\n');
        builder.Append("[global::System.CodeDom.Compiler.GeneratedCode(\"CmdStarter.Analyzers\", \"").Append(version).Append("\")]\n");
        builder.Append("internal sealed class ").Append(className).Append(" : ").Append(CatalogNamespace).Append(".ICommandCatalog\n");
        builder.Append("{\n");
        builder.Append("    public void Describe(").Append(CatalogNamespace).Append(".ICommandCatalogBuilder builder)\n");
        builder.Append("    {\n");
        foreach (var command in commands)
        {
            builder.Append("        builder.AddCommand<").Append(command).Append(">();\n");
        }

        foreach (var methodClass in methodClasses)
        {
            builder.Append("        builder.AddMethodCommands(typeof(").Append(methodClass).Append("));\n");
        }

        foreach (var container in globalOptions)
        {
            builder.Append("        builder.AddGlobalOptions<").Append(container).Append(">();\n");
        }

        foreach (var symbolType in symbolTypes)
        {
            builder.Append("        builder.AddSymbolType<").Append(symbolType).Append(">();\n");
        }

        builder.Append("    }\n");
        builder.Append("}\n");
        return builder.ToString();
    }
}
