    [Test]
    public void InaccessibleTypesAreLeftOutWithInfo()
    {
        var source = Usings + $$"""
            namespace Ns;
            public class Holder
            {
                private sealed class PrivateOne : StarterCommand {{Body}}
                protected sealed class ProtectedOne : StarterCommand {{Body}}
                private protected sealed class PrivateProtectedOne : StarterCommand {{Body}}
