    [Test]
    public void ObsoleteTypeWithItsOwnDiagnosticIdIsListedWithoutWarnings()
    {
        // The compiler reports the use of such a type under its own id (MYOLD001) and not under CS0618: the id has to be switched off in the generated file too.
        // An id of an enclosing type counts, and so does an id that is CS0618 itself (written once) or empty (the default id).
        var source = Usings + $$"""
            namespace Ns;
            [Obsolete("old", DiagnosticId = "MYOLD001")] public sealed class OldCommand : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MYOLD002")] public class Holder { public class OldOptions : IGlobalOptionsContainer { } }
            [Obsolete("old", DiagnosticId = "CS0618")] public sealed class SameId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "")] public sealed class EmptyId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "my_old3")] public sealed class Lower : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("#pragma warning disable CS0612, CS0618, MYOLD001, MYOLD002, my_old3\n"), "ids in ordinal order, once each");
        Assert.That(Calls(result), Is.EqualTo(new[]
        {
            "builder.AddCommand<global::Ns.EmptyId>();",
            "builder.AddCommand<global::Ns.Lower>();",
            "builder.AddCommand<global::Ns.OldCommand>();",
            "builder.AddCommand<global::Ns.SameId>();",
            "builder.AddGlobalOptions<global::Ns.Holder.OldOptions>();"
        }));
        Assert.That(result.GeneratedWarnings, Is.Empty);
        Assert.That(result.GeneratorDiagnostics, Is.Empty);
    }

    [Test]
    public void ObsoleteTypeWithAnUnwritableDiagnosticIdIsLeftOutWithInfo()
    {
        // An id with a space cannot be written in a #pragma: the type stays out of the catalog, as the other types the generated code could not name.
        // An id that starts with a digit is refused the same way.
        var source = Usings + $$"""
            namespace Ns;
            [Obsolete("old", DiagnosticId = "MY OLD")] public sealed class SpacedId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "1OLD")] public sealed class DigitFirst : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MY-OLD")] public sealed class Dashed : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MY[OLD")] public sealed class Bracket : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MYéOLD")] public sealed class Accented : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.Empty);
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(Enumerable.Repeat("CMDS0014", 5)));
        var messages = result.GeneratorDiagnostics.Select(diagnostic => diagnostic.GetMessage()).ToArray();
        Assert.That(messages, Has.Some.Contain("'SpacedId' is obsolete with the diagnostic id 'MY OLD', which cannot be suppressed in the catalog"));
    }

