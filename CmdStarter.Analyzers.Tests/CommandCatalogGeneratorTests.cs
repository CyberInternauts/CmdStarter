using CyberInternauts.CmdStarter.Analyzers;
using NUnit.Framework;

namespace CyberInternauts.CmdStarter.Analyzers.Tests;

/// <summary>The generator of the command catalog: what it lists, what it leaves out with CMDS0014, and that the result always compiles.</summary>
[TestFixture]
[Category("Analyzers")]
public sealed class CommandCatalogGeneratorTests
{
    private const string Usings = "using System;\nusing CyberInternauts.CmdStarter;\nusing CyberInternauts.CmdStarter.Attributes;\nusing CyberInternauts.CmdStarter.Interfaces;\n";

    private const string Body = "{ public override Delegate HandlingMethod => (Func<int>)(() => 0); }";

    [Test]
    public void NothingIsGeneratedWithoutCmdStarter()
    {
        var result = GeneratorRunner.Run("namespace Ns; public class Plain { }", includeCmdStarter: false);

        Assert.That(result.Generated, Is.Null);
        Assert.That(result.GeneratorDiagnostics, Is.Empty);
    }

    [Test]
    public void NothingIsGeneratedWithoutTheCatalogApi()
    {
        // A version of the library without catalogs: the command interface is there, the attribute of the catalog is not.
        var result = GeneratorRunner.Run("namespace CyberInternauts.CmdStarter.Interfaces { public interface IStarterCommand { } }\nnamespace Ns { public class Plain : CyberInternauts.CmdStarter.Interfaces.IStarterCommand { } }", includeCmdStarter: false);

        Assert.That(result.Generated, Is.Null);
    }

    [Test]
    public void OptionalTypesThatAreMissingAreTolerated()
    {
        // A library that has the catalog API but neither [Command] nor the global options container: commands are still listed, and no class declares method commands.
        var source = """
            namespace CyberInternauts.CmdStarter.Interfaces { public interface IStarterCommand { } }
            namespace CyberInternauts.CmdStarter.Catalog { public interface ICommandCatalog { } public sealed class CommandCatalogAttribute : System.Attribute { public CommandCatalogAttribute(System.Type type) { } } }
            namespace Ns { public sealed class Plain : CyberInternauts.CmdStarter.Interfaces.IStarterCommand { } public class Other { [System.Obsolete] public void Run() { } } }
            """;

        var result = GeneratorRunner.Run(source, includeCmdStarter: false);

        Assert.That(result.Generated, Is.Not.Null);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Plain>();" }));
    }

    [Test]
    public void EmptyCatalogIsGeneratedWithoutCommands()
    {
        var result = GeneratorRunner.Run(Usings + "namespace Ns; public class Plain { }");

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("[assembly: global::CyberInternauts.CmdStarter.Catalog.CommandCatalog(typeof(global::CyberInternauts.CmdStarter.Generated.CommandCatalog_GeneratorInput))]"));
        Assert.That(result.Generated, Does.Contain("// <auto-generated/>").And.Contain("#nullable enable").And.Contain("#pragma warning disable CS0612, CS0618"));
        Assert.That(result.Generated, Does.Contain("[global::System.CodeDom.Compiler.GeneratedCode(\"CmdStarter.Analyzers\", \""));
        Assert.That(Calls(result), Is.Empty);
    }

    [Test]
    public void ClassCommandsAreListed()
    {
        var source = Usings + $"namespace Zeta {{ public sealed class Second : StarterCommand {Body} }}\nnamespace Alpha {{ public sealed class First : StarterCommand {Body} }}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Alpha.First>();", "builder.AddCommand<global::Zeta.Second>();" }));
    }

    [Test]
    public void AbstractAndGlobalNamespaceAndOpenGenericClassesAreNotListed()
    {
        var source = Usings + $"namespace Ns {{ public abstract class Abstract : StarterCommand {Body} public class Open<T> : StarterCommand {Body} }}\npublic sealed class NoNamespace : StarterCommand {Body}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.Empty);
        // Only the open generic definition is reported: the scan found it, then failed to create it.
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(new[] { "CMDS0014" }));
        Assert.That(result.GeneratorDiagnostics[0].GetMessage(), Does.Contain("Open").And.Contain("open generic type definition"));
    }

    [Test]
    public void NestedClassIsListedWithItsOuterType()
    {
        var source = Usings + $"namespace Ns; public class Outer {{ public sealed class Inner : StarterCommand {Body} }}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Outer.Inner>();" }));
    }

    [Test]
    public void MethodCommandClassesAreListed()
    {
        var source = Usings + """
            namespace Ns;
            [Command("group")] public class OnClass { }
            public class OnPublicMethod { [Command] public int Run() => 0; }
            public class OnPrivateStatic { [Command] private static int Hidden() => 0; }
            public static class StaticHost { [Command] public static int Go() => 0; }
            public class Plain { public int NoCommand() => 0; }
            public class Derived : OnPublicMethod { }
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        // A static class is passed as a type, not as a type argument. [Command] is not inherited: Derived is not listed. The validation stays with the engine.
        Assert.That(Calls(result), Is.EqualTo(new[]
        {
            "builder.AddMethodCommands(typeof(global::Ns.OnClass));",
            "builder.AddMethodCommands(typeof(global::Ns.OnPrivateStatic));",
            "builder.AddMethodCommands(typeof(global::Ns.OnPublicMethod));",
            "builder.AddMethodCommands(typeof(global::Ns.StaticHost));"
        }));
    }

    [Test]
    public void InaccessibleTypesAreLeftOutWithInfo()
    {
        var source = Usings + $$"""
            namespace Ns;
            public class Holder
            {
                private sealed class PrivateOne : StarterCommand {{Body}}
                protected sealed class ProtectedOne : StarterCommand {{Body}}
                private protected sealed class PrivateProtectedOne : StarterCommand {{Body}}
                private class Outer { public sealed class InsideOne : StarterCommand {{Body}} }
                protected internal sealed class ProtectedInternalOne : StarterCommand {{Body}}
            }
            file sealed class FileOne : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Holder.ProtectedInternalOne>();" }), "protected internal stays reachable");
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(Enumerable.Repeat("CMDS0014", 5)));
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Severity), Is.All.EqualTo(Microsoft.CodeAnalysis.DiagnosticSeverity.Info));
        var messages = string.Join("\n", result.GeneratorDiagnostics.Select(diagnostic => diagnostic.GetMessage()));
        Assert.That(messages, Does.Contain("PrivateOne").And.Contain("ProtectedOne").And.Contain("PrivateProtectedOne").And.Contain("InsideOne").And.Contain("FileOne"));
        Assert.That(messages, Does.Contain("is private").And.Contain("is protected").And.Contain("is private protected").And.Contain("is file-local"));
        Assert.That(result.GeneratorDiagnostics.All(diagnostic => diagnostic.Location.IsInSource), Is.True);
    }

    [Test]
    public void TypesNestedInAGenericTypeAreLeftOutWithInfo()
    {
        var source = Usings + $"namespace Ns; public class Outer<T> {{ public sealed class Inner : StarterCommand {Body} }}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.Empty);
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(new[] { "CMDS0014" }));
        Assert.That(result.GeneratorDiagnostics[0].GetMessage(), Does.Contain("nested in the generic type"));
    }

    [Test]
    public void ObsoleteTypesAreListedWithoutWarnings()
    {
        var source = Usings + $"namespace Ns;\n[Obsolete] public sealed class OldCommand : StarterCommand {Body}\n[Obsolete(\"explicitly a warning\", false)] public sealed class OldExplicit : StarterCommand {Body}\n[Obsolete(\"use the new options\")] public class OldOptions : IGlobalOptionsContainer {{ }}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.OldCommand>();", "builder.AddCommand<global::Ns.OldExplicit>();", "builder.AddGlobalOptions<global::Ns.OldOptions>();" }));
        Assert.That(result.GeneratedWarnings, Is.Empty);
        Assert.That(result.GeneratorDiagnostics, Is.Empty);
    }

    [Test]
    public void ObsoleteTypeWithItsOwnDiagnosticIdIsListedWithoutWarnings()
    {
        // The compiler reports the use of such a type under its own id (MYOLD001) and not under CS0618: the id has to be switched off in the generated file too.
        // An id of an enclosing type counts, and so does an id that is CS0618 itself (written once) or empty (the default id).
        var source = Usings + $$"""
            namespace Ns;
            [Obsolete("old", DiagnosticId = "MYOLD001")] public sealed class OldCommand : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MYOLD002")] public class Holder { public class OldOptions : IGlobalOptionsContainer { } }
            [Obsolete("old", DiagnosticId = "CS0618")] public sealed class SameId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "")] public sealed class EmptyId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "my_old3")] public sealed class Lower : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("#pragma warning disable CS0612, CS0618, MYOLD001, MYOLD002, my_old3\n"), "ids in ordinal order, once each");
        Assert.That(Calls(result), Is.EqualTo(new[]
        {
            "builder.AddCommand<global::Ns.EmptyId>();",
            "builder.AddCommand<global::Ns.Lower>();",
            "builder.AddCommand<global::Ns.OldCommand>();",
            "builder.AddCommand<global::Ns.SameId>();",
            "builder.AddGlobalOptions<global::Ns.Holder.OldOptions>();"
        }));
        Assert.That(result.GeneratedWarnings, Is.Empty);
        Assert.That(result.GeneratorDiagnostics, Is.Empty);
    }

    [Test]
    public void ObsoleteTypeWithAnUnwritableDiagnosticIdIsLeftOutWithInfo()
    {
        // An id with a space cannot be written in a #pragma: the type stays out of the catalog, as the other types the generated code could not name.
        // An id that starts with a digit is refused the same way.
        var source = Usings + $$"""
            namespace Ns;
            [Obsolete("old", DiagnosticId = "MY OLD")] public sealed class SpacedId : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "1OLD")] public sealed class DigitFirst : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MY-OLD")] public sealed class Dashed : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MY[OLD")] public sealed class Bracket : StarterCommand {{Body}}
            [Obsolete("old", DiagnosticId = "MYéOLD")] public sealed class Accented : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.Empty);
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(Enumerable.Repeat("CMDS0014", 5)));
        var messages = result.GeneratorDiagnostics.Select(diagnostic => diagnostic.GetMessage()).ToArray();
        Assert.That(messages, Has.Some.Contain("'SpacedId' is obsolete with the diagnostic id 'MY OLD', which cannot be suppressed in the catalog"));
    }

    [Test]
    public void ErrorObsoleteAndExperimentalTypesAreLeftOutWithInfo()
    {
        var source = Usings + $$"""
            using System.Diagnostics.CodeAnalysis;
            namespace Ns;
            [Obsolete("gone", true)] public sealed class Gone : StarterCommand {{Body}}
            [Experimental("TEST0001")] public sealed class Lab : StarterCommand {{Body}}
            [Obsolete("gone", true)] public class GoneOptions : IGlobalOptionsContainer { }
            public class Holder { [Experimental("TEST0002")] public sealed class Inside : StarterCommand {{Body}} }
            public class Kept { [Obsolete("only a warning")] public sealed class Warned : StarterCommand {{Body}} }
            """;

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Kept.Warned>();" }));
        Assert.That(result.GeneratorDiagnostics.Select(diagnostic => diagnostic.Id), Is.EqualTo(Enumerable.Repeat("CMDS0014", 4)));
        var messages = string.Join("\n", result.GeneratorDiagnostics.Select(diagnostic => diagnostic.GetMessage()));
        Assert.That(messages, Does.Contain("is obsolete as an error").And.Contain("is experimental"));
    }

    [Test]
    public void HandWrittenCatalogSuppressesGeneration()
    {
        var source = Usings + $$"""
            using CyberInternauts.CmdStarter.Catalog;
            [assembly: CommandCatalog(typeof(Ns.MyCatalog))]
            namespace Ns;
            public sealed class MyCatalog : ICommandCatalog { public void Describe(ICommandCatalogBuilder builder) { } }
            public sealed class Hello : StarterCommand {{Body}}
            """;

        var result = GeneratorRunner.Run(source);

        // No second attribute (CS0579), no generated file.
        Assert.That(result.Generated, Is.Null);
        Assert.That(result.Errors, Is.Empty);
    }

    [Test]
    public void GlobalOptionsContainersAreListed()
    {
        var source = Usings + "namespace Ns { public class Options : IGlobalOptionsContainer { } public abstract class AbstractOptions : IGlobalOptionsContainer { } }\npublic class RootOptions : IGlobalOptionsContainer { }";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        // The abstract container and the container of the global namespace are listed: the scan of the containers asks neither.
        Assert.That(Calls(result), Is.EqualTo(new[]
        {
            "builder.AddGlobalOptions<global::Ns.AbstractOptions>();",
            "builder.AddGlobalOptions<global::Ns.Options>();",
            "builder.AddGlobalOptions<global::RootOptions>();"
        }));
    }

    [Test]
    public void CatalogNameFollowsTheAssemblyName()
    {
        var result = GeneratorRunner.Run(Usings + "namespace Ns; public class Plain { }", assemblyName: "My.App-Tests");

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("internal sealed class CommandCatalog_My_App_Tests : "));
    }

    [Test]
    public void CatalogNameKeepsUnderscoresAndDigits()
    {
        var result = GeneratorRunner.Run(Usings + "namespace Ns; public class Plain { }", assemblyName: "My_App2");

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("internal sealed class CommandCatalog_My_App2 : "));
    }

    [Test]
    public void CatalogOfAnAssemblyWithoutNameStillCompiles()
    {
        // The compiler always names the assembly of a project; a compilation made by hand may not.
        var result = GeneratorRunner.Run(Usings + "namespace Ns; public class Plain { }", assemblyName: null);

        AssertCompiles(result);
        Assert.That(result.Generated, Does.Contain("internal sealed class CommandCatalog_ : "));
    }

    [Test]
    public void InternalCommandIsListed()
    {
        var source = Usings + $"namespace Ns; internal sealed class Hidden : StarterCommand {Body}";

        var result = GeneratorRunner.Run(source);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Hidden>();" }));
    }

    [Test]
    public void TheCatalogCompilesWhenNullableIsOff()
    {
        var result = GeneratorRunner.Run(Usings + $"namespace Ns; public sealed class Hello : StarterCommand {Body}", nullable: false);

        AssertCompiles(result);
        Assert.That(Calls(result), Is.EqualTo(new[] { "builder.AddCommand<global::Ns.Hello>();" }));
    }

    // The calls that Describe makes, one per line, without their indentation.
    private static string[] Calls(GeneratorResult result) =>
        result.Generated!.Split('\n').Select(line => line.Trim()).Where(line => line.StartsWith("builder.", StringComparison.Ordinal)).ToArray();

    // The generated file must never break a valid compilation: no error, and no warning that comes from the generated file.
    private static void AssertCompiles(GeneratorResult result)
    {
        Assert.That(result.Generated, Is.Not.Null);
        Assert.That(result.Errors, Is.Empty, string.Join("\n", result.Errors));
        Assert.That(result.GeneratedWarnings, Is.Empty, string.Join("\n", result.GeneratedWarnings));
    }
}
